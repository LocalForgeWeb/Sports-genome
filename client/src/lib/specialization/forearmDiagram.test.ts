import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { coreForearmMuscleIds, forearmMuscleIds as m } from "@shared/specialization/ids";
import { forearmRegionData } from "@shared/specialization/regions/forearm";
import { forearmDiagram, forearmDiagramOutcrops } from "@shared/specialization/regions/forearm/diagram.generated";
import type { DiagramLayerId, DiagramPath, DiagramViewId } from "@shared/specialization/types";
import { flattenPath, polygonArea, type Point } from "@/components/specialization/diagramGeometry";
// The generator itself, so the committed asset is checked against what it produces.
import { renderModule } from "../../../../design/specialization/forearm/emit.mjs";

/**
 * The forearm drawing's manifest (brief §6 "Publish an SVG ID manifest and validate every
 * selectable path against the catalog"), its layer rules, and the anatomy it has to get
 * right: which side the thumb is on in each view, what is deep and what is surface.
 */

const asset = forearmDiagram;
const nodes = new Map(forearmRegionData.nodes.map((node) => [node.id, node] as const));
const VIEWS: DiagramViewId[] = ["palm", "back", "thumb"];
const LAYERS: DiagramLayerId[] = ["surface", "intermediate", "deep"];
const STRUCTURES = new Set(["skin", "bone", "outline"]);
const STRUCTURE_WORDS = new Set(["skin", "crease", "epicondyle", "humerus", "radius", "ulna", "olecranon", "membrane", "thumb"]);

type Placed = DiagramPath & { view: DiagramViewId; layer: DiagramLayerId };
const placed: Placed[] = VIEWS.flatMap((view) => LAYERS.flatMap((layer) => (asset.views[view]?.[layer]?.paths ?? []).map((path) => ({ ...path, view, layer }))));
const bellies = placed.filter((path) => path.kind === "belly");
const layerOf = (view: DiagramViewId, layer: DiagramLayerId) => asset.views[view]![layer]!;

function inside(point: Point, polygon: readonly Point[]): boolean {
  let hit = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const a = polygon[i];
    const b = polygon[j];
    if ((a.y > point.y) !== (b.y > point.y) && point.x < ((b.x - a.x) * (point.y - a.y)) / (b.y - a.y) + a.x) hit = !hit;
  }
  return hit;
}
const centroid = (path: DiagramPath): Point => {
  const points = flattenPath(path.d);
  return { x: points.reduce((sum, point) => sum + point.x, 0) / points.length, y: points.reduce((sum, point) => sum + point.y, 0) / points.length };
};
const bellyOf = (view: DiagramViewId, layer: DiagramLayerId, nodeId: string) => {
  const found = layerOf(view, layer).paths.filter((path) => path.kind === "belly" && path.nodeId === nodeId);
  expect(found.length, `${nodeId} has a belly in ${view}/${layer}`).toBeGreaterThan(0);
  return found.reduce((best, path) => (polygonArea(flattenPath(path.d)) > polygonArea(flattenPath(best.d)) ? path : best));
};

describe("the forearm drawing is the region's diagram", () => {
  it("is what the region data hands the page and the seed", () => {
    expect(forearmRegionData.diagram).toBe(forearmDiagram);
    expect(asset.regionId).toBe(forearmRegionData.region.id);
    expect(asset.viewBox).toEqual({ width: 360, height: 760 });
    expect(asset.licenseNote).toMatch(/^Original artwork drawn for Sports Genome/);
    expect(asset.licenseNote).toMatch(/Not traced or copied/);
  });

  it("is exactly what the generator writes (run node design/specialization/forearm/emit.mjs after a change)", () => {
    const committed = readFileSync(join(process.cwd(), "shared/specialization/regions/forearm/diagram.generated.ts"), "utf8");
    expect(committed).toBe(renderModule());
    expect(committed).toMatch(/^import type \{ DiagramAsset \}/);
    expect(committed).toContain("Generated by design/specialization/forearm/emit.mjs");
    expect(committed).toContain("Do not edit by hand");
  });

  it("has the views and layers anatomy has: a middle layer on the palm side only", () => {
    expect(Object.keys(asset.views).sort()).toEqual(["back", "palm", "thumb"]);
    expect(Object.keys(asset.views.palm!)).toEqual(["surface", "intermediate", "deep"]);
    expect(Object.keys(asset.views.back!)).toEqual(["surface", "deep"]);
    expect(Object.keys(asset.views.thumb!)).toEqual(["surface", "deep"]);
  });
});

describe("the path manifest", () => {
  it("gives every path a unique, well-formed id that names its view, layer and node", () => {
    const ids = placed.map((path) => path.id);
    expect(new Set(ids).size).toBe(ids.length);
    for (const path of placed) {
      const match = /^(palm|back|thumb)__(surface|intermediate|deep)__([a-z][a-z0-9-]*)__(\d+)$/.exec(path.id);
      expect(match, path.id).not.toBeNull();
      expect([match![1], match![2]], path.id).toEqual([path.view, path.layer]);
      if (path.nodeId) expect(match![3], path.id).toBe(nodes.get(path.nodeId)!.shortName.toLowerCase());
      else expect(STRUCTURE_WORDS.has(match![3]), path.id).toBe(true);
    }
  });

  it("numbers each name's paths from 1 in draw order", () => {
    for (const view of VIEWS) for (const layer of LAYERS) {
      const counts = new Map<string, number>();
      for (const path of asset.views[view]?.[layer]?.paths ?? []) {
        const name = path.id.split("__")[2];
        const next = (counts.get(name) ?? 0) + 1;
        expect(path.id.endsWith(`__${next}`), path.id).toBe(true);
        counts.set(name, next);
      }
    }
  });

  it("ties every belly, tendon and ghost to a node in the catalog, and structure to none", () => {
    for (const path of placed) {
      if (STRUCTURES.has(path.kind)) expect(path.nodeId, path.id).toBeNull();
      else {
        expect(path.nodeId, path.id).not.toBeNull();
        expect(nodes.has(path.nodeId!), `${path.id} → ${path.nodeId}`).toBe(true);
        expect(nodes.get(path.nodeId!)!.kind, path.id).toBe("muscle");
      }
    }
  });

  it("writes outlines as closed absolute curves the seed and any renderer can read", () => {
    for (const path of placed) {
      expect(path.d, path.id).toMatch(/^M[-\d. ]+( [CL][-\d. ]+)+( Z)?$/);
      if (path.kind !== "outline") expect(path.d.endsWith(" Z"), path.id).toBe(true);
      expect(path.d, `${path.id} is curved`).toContain(" C");
    }
  });

  it("draws one skin outline under everything else on every layer", () => {
    for (const view of VIEWS) for (const layer of LAYERS) {
      const drawn = asset.views[view]?.[layer];
      if (!drawn) continue;
      expect(drawn.paths[0].kind, `${view}/${layer}`).toBe("skin");
      expect(drawn.paths.filter((path) => path.kind === "skin")).toHaveLength(1);
    }
  });
});

describe("what is drawn where", () => {
  it("draws every one of the 19 core muscles as a belly somewhere", () => {
    const drawn = new Set(bellies.map((path) => path.nodeId));
    expect(coreForearmMuscleIds.filter((id) => !drawn.has(id))).toEqual([]);
  });

  it("draws a belly only on its muscle's own layer, apart from the listed outcrops", () => {
    const outcropIds = new Set(forearmDiagramOutcrops.map((item) => item.pathId));
    const offLayer = bellies.filter((path) => !outcropIds.has(path.id) && nodes.get(path.nodeId!)!.layer !== path.layer).map((path) => path.id);
    expect(offLayer).toEqual([]);
  });

  it("lists exactly the anatomical outcrops: APL and EPB surfacing above the wrist, on the back and from the thumb side", () => {
    expect(forearmDiagramOutcrops.map((item) => [item.nodeId, item.view, item.layer]).sort()).toEqual([
      [m.abductorPollicisLongus, "back", "surface"],
      [m.abductorPollicisLongus, "thumb", "surface"],
      [m.extensorPollicisBrevis, "back", "surface"],
      [m.extensorPollicisBrevis, "thumb", "surface"],
    ].sort());
    for (const item of forearmDiagramOutcrops) {
      const path = placed.find((candidate) => candidate.id === item.pathId);
      expect(path?.kind, item.pathId).toBe("belly");
      expect(path?.nodeId).toBe(item.nodeId);
      const node = nodes.get(item.nodeId)!;
      // Only a deep muscle that anatomy says reaches the surface may be drawn there.
      expect(node.layer).toBe("deep");
      expect(node.surfaceVisibility).not.toBe("not_distinct");
      expect(item.note.length).toBeGreaterThan(40);
      // Partial: the outcrop is much smaller than the muscle drawn whole in its own layer.
      const whole = bellyOf(item.view as DiagramViewId, "deep", item.nodeId);
      expect(polygonArea(flattenPath(path!.d))).toBeLessThan(polygonArea(flattenPath(whole.d)) * 0.75);
    }
  });

  it("keeps deep muscles off the surface (FDP, PQ, FPL, the thumb extensors, supinator, EI) and FDS to the middle layer", () => {
    const surfaceBellies = new Set(bellies.filter((path) => path.layer === "surface").map((path) => path.nodeId));
    for (const id of [m.flexorDigitorumProfundus, m.pronatorQuadratus, m.flexorPollicisLongus, m.extensorPollicisLongus, m.extensorIndicis, m.supinator, m.flexorDigitorumSuperficialis]) {
      expect(surfaceBellies.has(id), id).toBe(false);
    }
    expect(new Set(bellies.filter((path) => path.nodeId === m.flexorDigitorumSuperficialis).map((path) => `${path.view}/${path.layer}`))).toEqual(new Set(["palm/intermediate"]));
  });

  it("draws tendons apart from bellies, and never a tendon without its muscle somewhere in the drawing", () => {
    const tendons = placed.filter((path) => path.kind === "tendon");
    expect(tendons.length).toBeGreaterThan(30);
    const withBelly = new Set(bellies.map((path) => path.nodeId));
    expect(tendons.filter((path) => !withBelly.has(path.nodeId)).map((path) => path.id)).toEqual([]);
    // A tendon is narrow: far less area than its muscle's belly.
    for (const path of tendons) expect(polygonArea(flattenPath(path.d)), path.id).toBeLessThan(2200);
  });

  it("lets no two bellies on one layer overlap, and keeps each inside the arm's outline", () => {
    for (const view of VIEWS) for (const layer of LAYERS) {
      const drawn = asset.views[view]?.[layer];
      if (!drawn) continue;
      const skin = flattenPath(drawn.paths.find((path) => path.kind === "skin")!.d);
      const shapes = drawn.paths.filter((path) => path.kind === "belly").map((path) => ({ id: path.id, points: flattenPath(path.d) }));
      for (const shape of shapes) {
        const outside = shape.points.filter((point) => point.y > 0 && point.y < asset.viewBox.height && !inside(point, skin));
        expect(outside, `${shape.id} leaves the outline`).toEqual([]);
      }
      for (let i = 0; i < shapes.length; i++) for (let j = i + 1; j < shapes.length; j++) {
        const overlap = shapes[i].points.filter((point) => inside(point, shapes[j].points)).length + shapes[j].points.filter((point) => inside(point, shapes[i].points)).length;
        expect(overlap, `${shapes[i].id} overlaps ${shapes[j].id}`).toBe(0);
      }
    }
  });
});

describe("orientation, for the subject's right arm", () => {
  const W = asset.viewBox.width;
  const labelX = (view: DiagramViewId, text: string) => {
    for (const layer of LAYERS) {
      const drawn = asset.views[view]?.[layer];
      if (!drawn) continue;
      const label = drawn.labels.find((item) => item.text === text);
      expect(label, `${view}/${layer} labels "${text}"`).toBeDefined();
    }
    return asset.views[view]!.surface!.labels.find((item) => item.text === text)!.x;
  };

  it("labels the thumb side, the pinky side, the elbow and the wrist on every palm and back layer", () => {
    for (const view of ["palm", "back"] as const) for (const text of ["Thumb side", "Pinky side", "Elbow", "Wrist"]) labelX(view, text);
  });

  it("puts the thumb on the viewer's left from the palm side and on the right from behind", () => {
    expect(labelX("palm", "Thumb side")).toBeLessThan(W / 2);
    expect(labelX("palm", "Pinky side")).toBeGreaterThan(W / 2);
    expect(labelX("back", "Thumb side")).toBeGreaterThan(W / 2);
    expect(labelX("back", "Pinky side")).toBeLessThan(W / 2);
    // And the drawing agrees with its labels: brachioradialis is on the thumb side, flexor carpi ulnaris on the pinky side.
    expect(centroid(bellyOf("palm", "surface", m.brachioradialis)).x).toBeLessThan(centroid(bellyOf("palm", "surface", m.flexorCarpiUlnaris)).x);
    expect(centroid(bellyOf("back", "surface", m.extensorCarpiRadialisLongus)).x).toBeGreaterThan(centroid(bellyOf("back", "surface", m.extensorCarpiUlnaris)).x);
    // The thumb tendons run to the thumb side of the hand.
    const fplEnd = flattenPath(layerOf("palm", "deep").paths.find((path) => path.kind === "tendon" && path.nodeId === m.flexorPollicisLongus)!.d);
    expect(Math.min(...fplEnd.map((point) => point.x))).toBeLessThan(110);
  });

  it("names the palm side and the back side on the thumb-side view, palm side to the right", () => {
    for (const text of ["Palm side", "Back side", "Elbow", "Wrist"]) labelX("thumb", text);
    expect(labelX("thumb", "Palm side")).toBeGreaterThan(W / 2);
    expect(labelX("thumb", "Back side")).toBeLessThan(W / 2);
    expect(centroid(bellyOf("thumb", "surface", m.flexorCarpiRadialis)).x).toBeGreaterThan(centroid(bellyOf("thumb", "surface", m.extensorDigitorum)).x);
    expect(centroid(bellyOf("thumb", "deep", m.flexorPollicisLongus)).x).toBeGreaterThan(centroid(bellyOf("thumb", "deep", m.extensorPollicisLongus)).x);
  });

  it("keeps labels on the canvas and in its margins, clear of the arm", () => {
    for (const path of placed) void path;
    for (const view of VIEWS) for (const layer of LAYERS) {
      for (const label of asset.views[view]?.[layer]?.labels ?? []) {
        expect(label.x).toBeGreaterThanOrEqual(0);
        expect(label.x).toBeLessThanOrEqual(W);
        expect(label.y).toBeGreaterThan(0);
        expect(label.y).toBeLessThan(asset.viewBox.height);
      }
    }
  });

  it("puts proximal muscles near the elbow and distal ones near the wrist, the same in every view", () => {
    const y = (view: DiagramViewId, layer: DiagramLayerId, id: string) => centroid(bellyOf(view, layer, id)).y;
    expect(y("palm", "deep", m.supinator)).toBeLessThan(260);
    expect(y("back", "deep", m.supinator)).toBeLessThan(260);
    expect(y("thumb", "deep", m.supinator)).toBeLessThan(260);
    expect(y("palm", "deep", m.pronatorQuadratus)).toBeGreaterThan(500);
    expect(y("palm", "surface", m.pronatorTeres)).toBeLessThan(260);
    expect(y("back", "deep", m.extensorIndicis)).toBeGreaterThan(y("back", "deep", m.abductorPollicisLongus));
    // Brachioradialis starts above the elbow, on the ridge above the lateral epicondyle.
    for (const view of VIEWS) expect(Math.min(...flattenPath(bellyOf(view, "surface", m.brachioradialis).d).map((point) => point.y)), view).toBeLessThan(60);
  });
});
