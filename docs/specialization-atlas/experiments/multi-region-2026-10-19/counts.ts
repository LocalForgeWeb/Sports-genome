import { forearmRegionData as d } from "../../../../../../home/user/Sports-genome/shared/specialization/regions/forearm/index";
import { forearmDiagramOutcrops } from "../../../../../../home/user/Sports-genome/shared/specialization/regions/forearm/diagram.generated";
const tally = (xs: string[]) => xs.reduce((m, x) => ((m[x] = (m[x] ?? 0) + 1), m), {} as Record<string, number>);
const out: Record<string, unknown> = {};
out.nodes = d.nodes.length;
out.nodesByRole = tally(d.nodes.map((n) => n.role));
out.nodesByKind = tally(d.nodes.map((n) => n.kind));
out.nodesByLayer = tally(d.nodes.map((n) => n.layer));
out.nodesBySurface = tally(d.nodes.map((n) => n.surfaceVisibility));
out.nodesByRegion = tally(d.nodes.map((n) => n.regionId));
out.nodesWithCaveats = d.nodes.filter((n) => n.caveats.length).length;
out.caveats = d.nodes.reduce((s, n) => s + n.caveats.length, 0);
out.actions = d.actions.length;
out.actionsByJoint = tally(d.actions.map((a) => a.joint));
out.nodeActions = d.nodeActions.length;
out.nodeActionsByRole = tally(d.nodeActions.map((a) => a.role));
out.claims = d.claims.length;
out.claimsByKind = tally(d.claims.map((c) => c.kind));
out.claimsByBasis = tally(d.claims.map((c) => c.basis));
out.claimsByReview = tally(d.claims.map((c) => c.reviewStatus));
out.claimSourceRefs = d.claims.reduce((s, c) => s + c.sources.length, 0);
out.claimsWithOneSource = d.claims.filter((c) => c.sources.length === 1).map((c) => c.id);
out.claimRefsWithQualification = d.claims.flatMap((c) => c.sources).filter((r) => r.qualification).length;
out.claimRefsWithLocator = d.claims.flatMap((c) => c.sources).filter((r) => r.locator).length;
out.reviewNotes = tally(d.claims.map((c) => c.reviewNote ?? "null"));
out.reviewedAt = tally(d.claims.map((c) => c.reviewedAt ?? "null"));
out.meanClaimChars = Math.round(d.claims.reduce((s, c) => s + c.statement.length, 0) / d.claims.length);
out.sources = d.sources.length;
out.sourcesByPrefix = tally(d.sources.map((s) => s.id.replace(/\d+$/, "")));
out.sourcesByType = tally(d.sources.map((s) => s.evidenceType));
out.sourcesWithDoi = d.sources.filter((s) => s.doi).length;
out.sourceHosts = tally(d.sources.map((s) => new URL(s.url).hostname.replace(/^www\./, "")));
out.variants = d.variants.length;
out.variantsByOrg = tally(d.variants.map((v) => v.organization));
out.variantsByLaterality = tally(d.variants.map((v) => v.laterality));
out.variantsByMeasure = tally(d.variants.map((v) => v.measure));
out.variantsWithNotes = d.variants.filter((v) => v.notes).length;
out.mappings = d.mappings.length;
out.mappingsByRel = tally(d.mappings.map((m) => m.relationship));
out.mappingsByMode = tally(d.mappings.map((m) => m.muscleMode));
out.mappingsByBasis = tally(d.mappings.map((m) => m.evidenceBasis));
out.mappingsByAlloc = tally(d.mappings.map((m) => m.allocation));
out.mappingsByReview = tally(d.mappings.map((m) => m.reviewStatus));
out.mappingsNoStraps = d.mappings.filter((m) => m.requiresNoStraps).length;
out.mappingSourceRefs = d.mappings.reduce((s, m) => s + m.sources.length, 0);
out.distinctRationales = new Set(d.mappings.map((m) => m.rationale)).size;
out.mappingsPerNode = tally(d.mappings.map((m) => m.nodeId));
out.mappingSourceIdsUsed = tally(d.mappings.flatMap((m) => m.sources.map((r) => r.sourceId)));
out.mappingsToExternal = d.mappings.filter((m) => m.nodeId.startsWith("upper_arm.")).length;
const diagram = d.diagram!;
const layers: Record<string, unknown> = {};
let paths = 0, labels = 0;
for (const [view, ls] of Object.entries(diagram.views)) for (const [layer, l] of Object.entries(ls!)) {
  paths += l!.paths.length; labels += l!.labels.length;
  layers[`${view}/${layer}`] = { ...tally(l!.paths.map((p) => p.kind)), selectable: new Set(l!.paths.filter((p) => p.kind === "belly").map((p) => p.nodeId)).size };
}
out.diagram = { key: diagram.key, viewBox: diagram.viewBox, views: diagram.viewOrder, paths, labels, layers, outcrops: forearmDiagramOutcrops.length };
