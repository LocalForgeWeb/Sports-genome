/**
 * Writes shared/specialization/regions/forearm/diagram.generated.ts from the authored views.
 *
 *   node design/specialization/forearm/emit.mjs           # rewrite the file
 *   node design/specialization/forearm/emit.mjs --check   # exit 1 if the committed file is stale
 *
 * After a change, regenerate the database seed too (`npx tsx scripts/specialization/emit-seed.ts`):
 * the seed carries the drawing, and its drift guard fails until it is regenerated.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildAsset } from "./asset.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const target = resolve(root, "shared/specialization/regions/forearm/diagram.generated.ts");

const json = (value) => JSON.stringify(value);

export function renderModule() {
  const { asset, outcrops } = buildAsset();
  const lines = [];
  lines.push(`import type { DiagramAsset } from "../../types";`);
  lines.push("");
  lines.push("/**");
  lines.push(" * Generated by design/specialization/forearm/emit.mjs from the views in design/specialization/forearm/views/.");
  lines.push(" * Do not edit by hand: change the view and run `node design/specialization/forearm/emit.mjs`, then");
  lines.push(" * regenerate the database seed (`npx tsx scripts/specialization/emit-seed.ts`), which carries this drawing.");
  lines.push(" *");
  lines.push(" * The subject's RIGHT forearm; the renderer mirrors it for the left arm. Method and limits:");
  lines.push(" * docs/specialization-atlas/08-diagram.md.");
  lines.push(" */");
  lines.push("export const forearmDiagram: DiagramAsset = {");
  lines.push(`  key: ${json(asset.key)},`);
  lines.push(`  version: ${asset.version},`);
  lines.push(`  regionId: ${json(asset.regionId)},`);
  lines.push(`  viewBox: { width: ${asset.viewBox.width}, height: ${asset.viewBox.height} },`);
  lines.push("  views: {");
  for (const [view, layers] of Object.entries(asset.views)) {
    lines.push(`    ${view}: {`);
    for (const [layer, drawn] of Object.entries(layers)) {
      lines.push(`      ${layer}: {`);
      lines.push("        paths: [");
      for (const path of drawn.paths) lines.push(`          { id: ${json(path.id)}, nodeId: ${json(path.nodeId)}, kind: ${json(path.kind)}, d: ${json(path.d)} },`);
      lines.push("        ],");
      lines.push("        labels: [");
      for (const label of drawn.labels) lines.push(`          { text: ${json(label.text)}, x: ${label.x}, y: ${label.y}, anchor: ${json(label.anchor)} },`);
      lines.push("        ],");
      lines.push("      },");
    }
    lines.push("    },");
  }
  lines.push("  },");
  lines.push(`  licenseNote: ${json(asset.licenseNote)},`);
  lines.push("};");
  lines.push("");
  lines.push("/**");
  lines.push(" * Deep muscles drawn on a surface layer, and why: each is a partial outcrop where anatomy has the muscle");
  lines.push(" * come to the surface. Every other belly is drawn only on its node's own layer (tested in");
  lines.push(" * client/src/lib/specialization/forearmDiagram.test.ts).");
  lines.push(" */");
  lines.push("export const forearmDiagramOutcrops: readonly { pathId: string; nodeId: string; view: string; layer: string; note: string }[] = [");
  for (const item of outcrops) lines.push(`  { pathId: ${json(item.pathId)}, nodeId: ${json(item.nodeId)}, view: ${json(item.view)}, layer: ${json(item.layer)}, note: ${json(item.note)} },`);
  lines.push("];");
  lines.push("");
  return lines.join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const next = renderModule();
  if (process.argv.includes("--check")) {
    const current = readFileSync(target, "utf8");
    if (current !== next) { console.error(`${target} is stale: run node design/specialization/forearm/emit.mjs`); process.exit(1); }
    console.log("diagram.generated.ts is up to date");
  } else {
    writeFileSync(target, next);
    console.log(`wrote ${target} (${(next.length / 1024).toFixed(1)} KB)`);
  }
}
