/**
 * Writes a region's shared/specialization/regions/<region>/diagram.generated.ts from its
 * authored views (design/specialization/<region>/).
 *
 *   node design/specialization/shared/emit.mjs <region>           # rewrite the file
 *   node design/specialization/shared/emit.mjs <region> --check   # exit 1 if the committed file is stale
 *
 * After a change, regenerate the database seed too (`npx tsx scripts/specialization/emit-seed.ts`):
 * the seed carries the drawing, and its drift guard fails until it is regenerated.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { relative } from "node:path";
import { buildAsset } from "./asset.mjs";
import { generatedPath, loadDrawing, regionArgument, root } from "./region.mjs";

const json = (value) => JSON.stringify(value);

/** `upper_arm` → `upperArm`: the stem of the module's export names (`upperArmDiagram`, `upperArmDiagramOutcrops`). */
export const exportStem = (region) => region.replace(/_([a-z0-9])/g, (_, letter) => letter.toUpperCase());

/**
 * The words of the module's two comments, from the config's MODULE_TEXT where it has them (the
 * forearm keeps its own, so its file stays byte for byte as it was), else written for the region.
 */
function moduleText(config) {
  const region = config.REGION;
  const text = config.MODULE_TEXT ?? {};
  const command = text.command ?? `node design/specialization/shared/emit.mjs ${region}`;
  return {
    generator: text.generator ?? "design/specialization/shared/emit.mjs",
    command,
    drawn: text.drawn ?? (config.SIDES === "both_sides" ? "Both sides of the body, as seen; the renderer never mirrors it." : "The subject's RIGHT side; the renderer mirrors it for the left."),
    method: text.method ?? `docs/specialization-atlas/regions/${region}/diagram.md`,
    outcrops: text.outcrops ?? [
      "Muscles drawn on a layer above their own, and why: each is a partial outcrop where anatomy has the muscle",
      "show through. Every other belly is drawn only on its node's own layer (tested in",
      "client/src/lib/specialization/diagramContract.test.ts).",
    ],
  };
}

/** The module's text, exactly as committed. `views` is what the region's views/index.mjs builds; `members` its nodes. */
export function renderModule(config, views, members) {
  const { asset, outcrops } = buildAsset(config, views, members);
  const stem = exportStem(config.REGION);
  const text = moduleText(config);
  const lines = [];
  lines.push(`import type { DiagramAsset } from "../../types";`);
  lines.push("");
  lines.push("/**");
  lines.push(` * Generated by ${text.generator} from the views in design/specialization/${config.REGION}/views/.`);
  lines.push(` * Do not edit by hand: change the view and run \`${text.command}\`, then`);
  lines.push(" * regenerate the database seed (`npx tsx scripts/specialization/emit-seed.ts`), which carries this drawing.");
  lines.push(" *");
  lines.push(` * ${text.drawn} Method and limits:`);
  lines.push(` * ${text.method}.`);
  lines.push(" */");
  lines.push(`export const ${stem}Diagram: DiagramAsset = {`);
  lines.push(`  key: ${json(asset.key)},`);
  lines.push(`  version: ${asset.version},`);
  lines.push(`  regionId: ${json(asset.regionId)},`);
  lines.push(`  viewBox: { width: ${asset.viewBox.width}, height: ${asset.viewBox.height} },`);
  // Written only where the config sets a side policy, so a drawing without one is unchanged.
  if (asset.sides) lines.push(`  sides: ${json(asset.sides)},`);
  lines.push(`  viewOrder: [${asset.viewOrder.map((view) => `{ id: ${json(view.id)}, label: ${json(view.label)} }`).join(", ")}],`);
  lines.push("  views: {");
  for (const [view, layers] of Object.entries(asset.views)) {
    lines.push(`    ${view}: {`);
    for (const [layer, drawn] of Object.entries(layers)) {
      lines.push(`      ${layer}: {`);
      lines.push("        paths: [");
      for (const path of drawn.paths) lines.push(`          { id: ${json(path.id)}, nodeId: ${json(path.nodeId)}, kind: ${json(path.kind)}, d: ${json(path.d)} },`);
      lines.push("        ],");
      lines.push("        labels: [");
      for (const label of drawn.labels) lines.push(`          { text: ${json(label.text)}, x: ${label.x}, y: ${label.y}, anchor: ${json(label.anchor)} },`);
      lines.push("        ],");
      lines.push("      },");
    }
    lines.push("    },");
  }
  lines.push("  },");
  lines.push(`  licenseNote: ${json(asset.licenseNote)},`);
  lines.push("};");
  lines.push("");
  lines.push("/**");
  for (const line of text.outcrops) lines.push(` * ${line}`);
  lines.push(" */");
  lines.push(`export const ${stem}DiagramOutcrops: readonly { pathId: string; nodeId: string; view: string; layer: string; note: string }[] = [`);
  for (const item of outcrops) lines.push(`  { pathId: ${json(item.pathId)}, nodeId: ${json(item.nodeId)}, view: ${json(item.view)}, layer: ${json(item.layer)}, note: ${json(item.note)} },`);
  lines.push("];");
  lines.push("");
  return lines.join("\n");
}

/** `emit <region> [--check]`: writes the region's module, or with --check exits 1 if the committed one differs. */
export async function emit(region, check) {
  const { config, views, members } = await loadDrawing(region);
  const target = generatedPath(region);
  const next = renderModule(config, views, members);
  if (check) {
    let current = null;
    try {
      current = readFileSync(target, "utf8");
    } catch {
      current = null;
    }
    if (current !== next) {
      console.error(`${relative(root, target)} is stale: run ${moduleText(config).command}`);
      process.exit(1);
    }
    console.log(`${relative(root, target)} is up to date`);
  } else {
    writeFileSync(target, next);
    console.log(`wrote ${target} (${(next.length / 1024).toFixed(1)} KB)`);
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  await emit(regionArgument(args, "node design/specialization/shared/emit.mjs <region> [--check]"), args.includes("--check"));
}
